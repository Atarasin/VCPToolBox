function parseArgs(argv) {
    const parsed = {
        agentId: DEFAULT_AGENT_ID,
        userName: DEFAULT_USER_NAME,
        serverName: DEFAULT_SERVER_NAME,
        codexBin: process.env.CODEX_BIN || DEFAULT_CODEX_BIN,
        model: process.env.CODEX_MODEL || '',
        keepTemp: false,
        help: false
    };

    for (let index = 0; index < argv.length; index += 1) {
        const argument = argv[index];
        if (argument === '--help') {
            parsed.help = true;
            continue;
        }
        if (argument === '--keep-temp') {
            parsed.keepTemp = true;
            continue;
        }

        const nextValue = argv[index + 1];
        if (!nextValue) {
            throw new Error(`Missing value for ${argument}`);
        }

        if (argument === '--agent-id') {
            parsed.agentId = nextValue.trim() || DEFAULT_AGENT_ID;
            index += 1;
            continue;
        }
        if (argument === '--user-name') {
            parsed.userName = nextValue.trim() || DEFAULT_USER_NAME;
            index += 1;
            continue;
        }
        if (argument === '--server-name') {
            parsed.serverName = nextValue.trim() || DEFAULT_SERVER_NAME;
            index += 1;
            continue;
        }
        if (argument === '--codex-bin') {
            parsed.codexBin = nextValue.trim() || DEFAULT_CODEX_BIN;
            index += 1;
            continue;
        }
        if (argument === '--model') {
            parsed.model = nextValue.trim();
            index += 1;
            continue;
        }

        throw new Error(`Unsupported argument: ${argument}`);
    }

    return parsed;
}

function escapeTomlString(value) {
    return String(value)
        .replaceAll('\\', '\\\\')
        .replaceAll('"', '\\"');
}

function createCodexConfigToml({
    serverName,
    mcpUrl,
    gatewayKey,
    gatewayId
}) {
    return [
        `# Auto-generated by scripts/run-agent-gateway-codex-e2e.js`,
        `[mcp_servers.${serverName}]`,
        `url = "${escapeTomlString(mcpUrl)}"`,
        `http_headers = { "x-agent-gateway-key" = "${escapeTomlString(gatewayKey)}", "x-agent-gateway-id" = "${escapeTomlString(gatewayId)}" }`,
        'startup_timeout_sec = 15',
        'tool_timeout_sec = 90',
        'required = true',
        'enabled_tools = ["gateway_agent_bootstrap"]',
        ''
    ].join('\n');
}

function composeCodexConfig(existingConfig, generatedConfig) {
    const trimmedExistingConfig = String(existingConfig || '').trim();
    const trimmedGeneratedConfig = String(generatedConfig || '').trim();

    if (!trimmedExistingConfig) {
        return `${trimmedGeneratedConfig}\n`;
    }
    if (!trimmedGeneratedConfig) {
        return `${trimmedExistingConfig}\n`;
    }

    return `${trimmedExistingConfig}\n\n${trimmedGeneratedConfig}\n`;
}

function stripInheritedMcpSections(configText) {
    const lines = String(configText || '').split('\n');
    const keptLines = [];
    let skipCurrentSection = false;

    for (const line of lines) {
        const sectionMatch = line.match(/^\s*\[([^\]]+)\]\s*$/);
        if (sectionMatch) {
            const sectionName = sectionMatch[1].trim();
            skipCurrentSection = sectionName.startsWith('mcp_servers.');
        }

        if (!skipCurrentSection) {
            keptLines.push(line);
        }
    }

    return keptLines.join('\n').trim();
}

function createCodexPrompt({
    agentId,
    userName
}) {
    return [
        'You are running an MCP connectivity self-test for a Streamable HTTP server.',
        'Mandatory steps:',
        '1. Use the MCP tool `gateway_agent_bootstrap`.',
        `2. Call it with arguments {"agentId":"${agentId}","variables":{"VarUserName":"${userName}"}}.`,
        '3. Do not paraphrase or summarize the tool result.',
        '4. Reply with exactly one line in this format:',
        'BOOTSTRAP_OK::<renderedPrompt>',
        'If the tool is unavailable or the call fails, reply with exactly one line:',
        'BOOTSTRAP_FAIL::<reason>'
    ].join('\n');
}

function readRenderTextFromToolCall(toolCallResult) {
    return String(
        toolCallResult?.body?.result?.structuredContent?.result?.renderedPrompt
        || toolCallResult?.body?.result?.content?.[0]?.text
        || ''
    );
}

async function readResponse(response) {
    const rawBody = await response.text();
    let body = null;
    if (rawBody) {
        try {
            body = JSON.parse(rawBody);
        } catch (_error) {
            body = null;
        }
    }
    return {
        status: response.status,
        headers: Object.fromEntries(response.headers.entries()),
        body,
        rawBody
    };
}

async function postJson(url, body, options = {}) {
    const response = await fetch(url, {
        method: 'POST',
        headers: {
            accept: 'application/json, text/event-stream',
            'content-type': 'application/json',
            'mcp-protocol-version': DEFAULT_MCP_PROTOCOL_VERSION,
            ...(options.headers || {})
        },
        body: JSON.stringify(body)
    });
    return readResponse(response);
}

async function runDirectGatewayProbe({
    mcpUrl,
    gatewayKey,
    gatewayId,
    agentId,
    userName
}) {
    const sharedHeaders = {
        'x-agent-gateway-key': gatewayKey,
        'x-agent-gateway-id': gatewayId
    };
    const issues = [];
    const initialize = await postJson(mcpUrl, {
        jsonrpc: '2.0',
        id: 'init-1',
        method: 'initialize',
        params: {
            protocolVersion: DEFAULT_MCP_PROTOCOL_VERSION,
            capabilities: {},
            clientInfo: {
                name: 'agent-gateway-codex-e2e',
                version: '1.0.0'
            }
        }
    }, {
        headers: sharedHeaders
    });

    const sessionId = initialize.headers['mcp-session-id'] || '';
    if (initialize.status !== 200) {
        issues.push(`initialize returned ${initialize.status}`);
    }
    if (!sessionId) {
        issues.push('initialize response did not include `MCP-Session-Id`');
    }

    const sessionHeaders = {
        ...sharedHeaders,
        ...(sessionId ? { 'mcp-session-id': sessionId } : {})
    };
    const initialized = await postJson(mcpUrl, {
        jsonrpc: '2.0',
        method: 'notifications/initialized'
    }, {
        headers: sessionHeaders
    });
    if (initialized.status !== 202) {
        issues.push(`notifications/initialized returned ${initialized.status}`);
    }
    if (initialized.rawBody) {
        issues.push('notifications/initialized returned an unexpected response body');
    }

    const toolsList = await postJson(mcpUrl, {
        jsonrpc: '2.0',
        id: 'tools-1',
        method: 'tools/list'
    }, {
        headers: sessionHeaders
    });
    const toolNames = Array.isArray(toolsList.body?.result?.tools)
        ? toolsList.body.result.tools.map((tool) => tool.name)
        : [];
    if (toolsList.status !== 200) {
        issues.push(`tools/list returned ${toolsList.status}`);
    }
    if (!toolNames.includes('gateway_agent_bootstrap')) {
        issues.push('tools/list did not expose `gateway_agent_bootstrap`');
    }

    const toolCall = await postJson(mcpUrl, {
        jsonrpc: '2.0',
        id: 'call-1',
        method: 'tools/call',
        params: {
            name: 'gateway_agent_bootstrap',
            arguments: {
                agentId,
                variables: {
                    VarUserName: userName
                }
            }
        }
    }, {
        headers: sessionHeaders
    });
    const renderedPrompt = readRenderTextFromToolCall(toolCall);
    if (toolCall.status !== 200) {
        issues.push(`tools/call returned ${toolCall.status}`);
    }
    if (!renderedPrompt) {
        issues.push('tools/call did not return a rendered prompt');
    }
    if (renderedPrompt && !renderedPrompt.includes(`Hello ${userName}`)) {
        issues.push('tools/call returned a rendered prompt without the expected bootstrap payload');
    }

    return {
        ok: issues.length === 0,
        issues,
        initialize,
        initialized,
        toolsList,
        toolCall,
        sessionId,
        renderedPrompt
    };
}

function evaluateRun({
    mcpGetResult,
    directProbe,
    execResult,
    lastMessage,
    renderHits,
    userName
}) {
    const issues = [];
    const warnings = [];
    const normalizedStdout = `${mcpGetResult?.stdout || ''}\n${mcpGetResult?.stderr || ''}`;
    const normalizedExecOutput = `${execResult?.stdout || ''}\n${execResult?.stderr || ''}\n${lastMessage || ''}`;

    if (!mcpGetResult || mcpGetResult.code !== 0) {
        issues.push('`codex mcp get` failed');
    }
    if (!/streamable_http|url\s*=|url:/i.test(normalizedStdout)) {
        issues.push('`codex mcp get` output did not include the expected HTTP server details');
    }
    if (!directProbe || !directProbe.ok) {
        issues.push(
            ...((directProbe?.issues || ['Direct Streamable HTTP bootstrap probe failed'])
                .map((issue) => `Direct MCP probe: ${issue}`))
        );
    }
    if (!Number.isFinite(renderHits) || renderHits < 1) {
        issues.push('Codex did not trigger the backend render route');
    }

    const lastMessageText = String(lastMessage || '');
    const directProbePrompt = String(directProbe?.renderedPrompt || '');
    if (lastMessageText.startsWith('BOOTSTRAP_OK::') && lastMessageText.includes(`Hello ${userName}`)) {
        return {
            ok: issues.length === 0,
            issues,
            warnings
        };
    }

    if (/user cancelled MCP tool call/i.test(normalizedExecOutput)) {
        warnings.push('Codex exec cancelled the MCP tool call in non-interactive mode; direct MCP probe evidence is used for pass/fail.');
    } else if (directProbePrompt) {
        warnings.push('Codex exec did not emit a BOOTSTRAP_OK marker; direct MCP probe evidence is used for pass/fail.');
    } else {
        issues.push('Neither Codex exec nor the direct probe produced the expected rendered prompt payload');
    }

    return {
        ok: issues.length === 0,
        issues,
        warnings
    };
}

function detectCodexAuthFailure(execResult) {
    const combinedOutput = `${execResult?.stdout || ''}\n${execResult?.stderr || ''}`;
    return /401 Unauthorized|Missing bearer or basic authentication|codex login|api\.openai\.com\/v1\/responses/i.test(
        combinedOutput
    );
}

function resolveCodexAuthHint() {
    if (process.env.OPENAI_API_KEY) {
        return 'Detected Codex authentication failure even though `OPENAI_API_KEY` is present in the current process. Re-check whether the key is valid for this Codex provider/account.';
    }
    return 'Detected Codex authentication failure. If you use API key auth, export `OPENAI_API_KEY` in the same shell before retrying; otherwise run `codex login`.';
}

function resolveExistingCodexHome() {
    const configuredHome = typeof process.env.CODEX_HOME === 'string'
        ? process.env.CODEX_HOME.trim()
        : '';
    return configuredHome || path.join(os.homedir(), '.codex');
}

async function createTempAgentDir(baseDir) {
    const targetPath = path.join(baseDir, 'agent-fixture');
    await fs.mkdir(targetPath, { recursive: true });
    return targetPath;
}

async function writeAgentFile(baseDir, relativePath, content) {
    const absolutePath = path.join(baseDir, relativePath);
    await fs.mkdir(path.dirname(absolutePath), { recursive: true });
    await fs.writeFile(absolutePath, content, 'utf8');
}

function createAgentManager(agentDir, mappings = {
    [DEFAULT_AGENT_ID]: `${DEFAULT_AGENT_ID}.md`
}) {
    const agentMap = new Map(Object.entries(mappings));

    return {
        agentDir,
        agentMap,
        isAgent(alias) {
            return agentMap.has(alias);
        },
        async getAgentPrompt(alias) {
            const sourceFile = agentMap.get(alias);
            return fs.readFile(path.join(agentDir, sourceFile), 'utf8');
        },
        async getAllAgentFiles() {
            return {
                files: Array.from(agentMap.values()),
                folderStructure: {}
            };
        }
    };
}

function createRenderPluginManager(agentDir, {
    agentId,
    gatewayKey,
    gatewayId
}) {
    return createPluginManager({
        agentManager: createAgentManager(agentDir, {
            [agentId]: `${agentId}.md`
        }),
        agentGatewayProtocolConfig: {
            gatewayKey,
            gatewayId
        },
        agentRegistryRenderPrompt: async ({ rawPrompt, renderVariables }) =>
            rawPrompt.replaceAll('{{VarUserName}}', renderVariables.VarUserName || '')
    });
}

async function startServer(app) {
    const server = http.createServer(app);
    await new Promise((resolve) => {
        server.listen(0, '127.0.0.1', resolve);
    });
    return server;
}

async function startNativeBackend(pluginManager) {
    const app = express();
    const metrics = {
        renderHits: 0,
        requests: []
    };

    app.use(express.json());
    // Track real render hits to prove Codex exercised the backend through the MCP transport.
    app.use('/agent_gateway/agents/:agentId/render', (req, _res, next) => {
        if (req.method === 'POST') {
            metrics.renderHits += 1;
        }
        metrics.requests.push({
            method: req.method,
            path: req.originalUrl,
            agentId: req.params.agentId || '',
            status: null
        });
        next();
    });
    app.use('/agent_gateway', createAgentGatewayRoutes(pluginManager));

    const server = await startServer(app);
    return {
        metrics,
        baseUrl: `http://127.0.0.1:${server.address().port}`,
        async close() {
            await new Promise((resolve, reject) => {
                server.close((error) => {
                    if (error) {
                        reject(error);
                        return;
                    }
                    resolve();
                });
            });
        }
    };
}

async function startMcpHttpGateway({
    pluginManager,
    backendUrl,
    defaultAgentId,
    gatewayKey,
    gatewayId
}) {
    const app = express();
    const metrics = {
        requests: []
    };
    const manager = createMcpHttpServer({
        pluginManager,
        backendUrl,
        defaultAgentId,
        gatewayKey,
        gatewayId,
        stderr: process.stderr
    });

    app.use('/mcp', (req, res, next) => {
        const entry = {
            method: req.method,
            path: req.originalUrl,
            accept: String(req.headers.accept || ''),
            contentType: String(req.headers['content-type'] || ''),
            protocolVersion: String(req.headers['mcp-protocol-version'] || ''),
            sessionId: String(req.headers['mcp-session-id'] || ''),
            status: null
        };
        metrics.requests.push(entry);
        res.on('finish', () => {
            entry.status = res.statusCode;
        });
        next();
    });
    manager.attach(app);
    const server = await startServer(app);
    return {
        metrics,
        mcpUrl: `http://127.0.0.1:${server.address().port}/mcp`,
        async close() {
            await manager.close();
            await new Promise((resolve, reject) => {
                server.close((error) => {
                    if (error) {
                        reject(error);
                        return;
                    }
                    resolve();
                });
            });
        }
    };
}

function runCommand(command, args, options = {}) {
    return new Promise((resolve, reject) => {
        const child = spawn(command, args, {
            cwd: options.cwd || process.cwd(),
            env: {
                ...process.env,
                ...(options.env || {})
            },
            stdio: ['ignore', 'pipe', 'pipe']
        });

        let stdout = '';
        let stderr = '';
        child.stdout.setEncoding('utf8');
        child.stderr.setEncoding('utf8');
        child.stdout.on('data', (chunk) => {
            stdout += chunk;
        });
        child.stderr.on('data', (chunk) => {
            stderr += chunk;
        });
        child.on('error', reject);
        child.on('close', (code) => {
            resolve({
                code,
                stdout,
                stderr
            });
        });
    });
}

async function readIfExists(filePath) {
    try {
        return await fs.readFile(filePath, 'utf8');
    } catch (error) {
        if (error && error.code === 'ENOENT') {
            return '';
        }
        throw error;
    }
}

async function copyFileIfExists(sourcePath, targetPath) {
    try {
        await fs.copyFile(sourcePath, targetPath);
        return true;
    } catch (error) {
        if (error && error.code === 'ENOENT') {
            return false;
        }
        throw error;
    }
}

async function removeDirectoryIfNeeded(directoryPath) {
    if (!directoryPath) {
        return;
    }
    await fs.rm(directoryPath, {
        recursive: true,
        force: true
    });
}

async function main(argv = process.argv.slice(2)) {
    const options = parseArgs(argv);
    if (options.help) {
        printUsage();
        return 0;
    }

    const tempBaseDir = path.join(process.cwd(), '.tmp');
    await fs.mkdir(tempBaseDir, { recursive: true });
    const tempRoot = await fs.mkdtemp(path.join(tempBaseDir, 'agw-codex-e2e-'));
    const codexHome = path.join(tempRoot, 'codex-home');
    const lastMessagePath = path.join(tempRoot, 'codex-last-message.txt');
    const existingCodexHome = resolveExistingCodexHome();
    let agentDir = '';
    let nativeBackend = null;
    let mcpGateway = null;

    try {
        await fs.mkdir(codexHome, { recursive: true });
        const existingConfigPath = path.join(existingCodexHome, 'config.toml');
        const existingAuthPath = path.join(existingCodexHome, 'auth.json');
        const existingConfig = stripInheritedMcpSections(await readIfExists(existingConfigPath));
        await copyFileIfExists(existingAuthPath, path.join(codexHome, 'auth.json'));

        agentDir = await createTempAgentDir(tempRoot);
        await writeAgentFile(
            agentDir,
            `${options.agentId}.md`,
            `You are ${options.agentId}. Hello {{VarUserName}}.`
        );

        const pluginManager = createRenderPluginManager(agentDir, {
            agentId: options.agentId,
            gatewayKey: DEFAULT_GATEWAY_KEY,
            gatewayId: DEFAULT_GATEWAY_ID
        });
        nativeBackend = await startNativeBackend(pluginManager);
        mcpGateway = await startMcpHttpGateway({
            pluginManager,
            backendUrl: nativeBackend.baseUrl,
            defaultAgentId: options.agentId,
            gatewayKey: DEFAULT_GATEWAY_KEY,
            gatewayId: DEFAULT_GATEWAY_ID
        });

        await fs.writeFile(
            path.join(codexHome, 'config.toml'),
            composeCodexConfig(existingConfig, createCodexConfigToml({
                serverName: options.serverName,
                mcpUrl: mcpGateway.mcpUrl,
                gatewayKey: DEFAULT_GATEWAY_KEY,
                gatewayId: DEFAULT_GATEWAY_ID
            })),
            'utf8'
        );

        const sharedEnv = {
            CODEX_HOME: codexHome
        };

        const mcpGetResult = await runCommand(options.codexBin, [
            'mcp',
            'get',
            options.serverName
        ], {
            cwd: process.cwd(),
            env: sharedEnv
        });
        const directProbe = await runDirectGatewayProbe({
            mcpUrl: mcpGateway.mcpUrl,
            gatewayKey: DEFAULT_GATEWAY_KEY,
            gatewayId: DEFAULT_GATEWAY_ID,
            agentId: options.agentId,
            userName: options.userName
        });

        const execArgs = [
            'exec',
            '--skip-git-repo-check',
            '--ephemeral',
            '--sandbox',
            'read-only',
            '--color',
            'never',
            '--cd',
            process.cwd(),
            '--output-last-message',
            lastMessagePath
        ];
        if (options.model) {
            execArgs.push('--model', options.model);
        }
        execArgs.push(createCodexPrompt({
            agentId: options.agentId,
            userName: options.userName
        }));

        const execResult = await runCommand(options.codexBin, execArgs, {
            cwd: process.cwd(),
            env: sharedEnv
        });
        const lastMessage = (await readIfExists(lastMessagePath)).trim();
        const evaluation = evaluateRun({
            mcpGetResult,
            directProbe,
            execResult,
            lastMessage,
            renderHits: nativeBackend.metrics.renderHits,
            userName: options.userName
        });

        if (execResult.code !== 0) {
            const authHint = detectCodexAuthFailure(execResult)
                ? resolveCodexAuthHint()
                : null;
            throw new Error([
                'codex exec failed.',
                ...(authHint ? ['', authHint] : []),
                '',
                `exitCode=${execResult.code}`,
                `stdout:\n${execResult.stdout.trim() || '(empty)'}`,
                `stderr:\n${execResult.stderr.trim() || '(empty)'}`,
                `tempRoot=${tempRoot}`
            ].join('\n\n'));
        }

        if (!evaluation.ok) {
            throw new Error([
                'Codex MCP E2E validation failed.',
                ...evaluation.issues.map((issue) => `- ${issue}`),
                ...(evaluation.warnings.length > 0
                    ? ['', ...evaluation.warnings.map((warning) => `! ${warning}`)]
                    : []),
                '',
                `codex mcp get stdout:\n${mcpGetResult.stdout.trim() || '(empty)'}`,
                `codex mcp get stderr:\n${mcpGetResult.stderr.trim() || '(empty)'}`,
                `direct probe summary:\n${JSON.stringify({
                    ok: directProbe.ok,
                    issues: directProbe.issues,
                    sessionId: directProbe.sessionId,
                    renderedPrompt: directProbe.renderedPrompt
                }, null, 2)}`,
                `codex exec stdout:\n${execResult.stdout.trim() || '(empty)'}`,
                `codex exec stderr:\n${execResult.stderr.trim() || '(empty)'}`,
                `last message:\n${lastMessage || '(empty)'}`,
                `renderHits=${nativeBackend.metrics.renderHits}`,
                `gatewayRequests=${JSON.stringify(mcpGateway.metrics.requests, null, 2)}`,
                `backendRequests=${JSON.stringify(nativeBackend.metrics.requests, null, 2)}`,
                `tempRoot=${tempRoot}`
            ].join('\n'));
        }

        process.stdout.write([
            '[Codex MCP E2E] PASS',
            `server=${options.serverName}`,
            `mcpUrl=${mcpGateway.mcpUrl}`,
            `renderHits=${nativeBackend.metrics.renderHits}`,
            `directProbeSession=${directProbe.sessionId}`,
            `directProbePrompt=${directProbe.renderedPrompt}`,
            `lastMessage=${lastMessage}`
        ].concat(
            evaluation.warnings.map((warning) => `warning=${warning}`)
        ).join('\n') + '\n');

        if (!options.keepTemp) {
            await removeDirectoryIfNeeded(agentDir);
            await removeDirectoryIfNeeded(tempRoot);
        } else {
            process.stdout.write(`[Codex MCP E2E] kept temp files at ${tempRoot}\n`);
        }
        return 0;
    } catch (error) {
        process.stderr.write(`${error.message || String(error)}\n`);
        if (!options.keepTemp) {
            process.stderr.write(`[Codex MCP E2E] temp files kept for inspection: ${tempRoot}\n`);
        }
        return 1;
    } finally {
        if (mcpGateway) {
            await mcpGateway.close().catch(() => {});
        }
        if (nativeBackend) {
            await nativeBackend.close().catch(() => {});
        }
    }
}

